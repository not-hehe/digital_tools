HEALTHY_MIN = 200
HEALTHY_MAX = 400

MSK = timezone(timedelta(hours=3))


def now_msk() -> datetime:
    """Текущее московское время без пометки о зоне.

    Живёт рядом с MSK, потому что зона и способ её применить это одно
    решение. Время наивное (без tzinfo): отметки уходят в сообщения и в файл
    состояния, и лишняя зона там только мешает читать.
    """
    return datetime.now(tz=MSK).replace(tzinfo=None)

